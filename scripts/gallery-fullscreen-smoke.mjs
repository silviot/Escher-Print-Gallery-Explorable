#!/usr/bin/env node
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.GALLERY_URL || 'http://127.0.0.1:5186/gallery/';
const browser = await chromium.launch({ executablePath:process.env.CHROME_PATH || undefined, args:['--no-sandbox', '--enable-unsafe-swiftshader'] });
try {
  const errors=[];
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  page.on('pageerror', error=>errors.push(error.message));
  await page.goto(base, {waitUntil:'networkidle'});
  await page.locator('.artwork-stage[data-ready="true"]').waitFor();
  await page.locator('.expand').click();
  await page.locator('.cinema.immersive').waitFor();
  await page.waitForTimeout(350);
  assert(await page.evaluate(()=>document.fullscreenElement?.classList.contains('cinema')), 'Whole gallery enters native fullscreen');
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden');
  if (process.env.GALLERY_SHOT_DIR) await page.screenshot({path:`${process.env.GALLERY_SHOT_DIR}/cinema-fullscreen-desktop.png`});
  await page.waitForTimeout(3600);
  assert(await page.locator('.cinema').evaluate(el=>el.classList.contains('controls-hidden')), 'Autoplay hides idle controls');
  if (process.env.GALLERY_SHOT_DIR) await page.screenshot({path:`${process.env.GALLERY_SHOT_DIR}/cinema-fullscreen-idle.png`});
  await page.keyboard.press('Space');
  assert.equal(await page.locator('.cinema').getAttribute('data-touring'),'false');
  assert(!await page.locator('.cinema').evaluate(el=>el.classList.contains('controls-hidden')), 'Pause reveals controls');
  await page.keyboard.press('Space');
  assert.equal(await page.locator('.cinema').getAttribute('data-touring'),'true');
  await page.locator('.collection-toggle').click();
  assert(await page.locator('.collection').evaluate(el=>el.classList.contains('open')));
  assert.equal(await page.locator('.cinema').getAttribute('data-touring'),'false');
  await page.locator('.filmstrip button').nth(4).click();
  await page.locator('.artwork-stage[data-ready="true"]').waitFor();
  assert(!await page.locator('.collection').evaluate(el=>el.classList.contains('open')));
  await page.keyboard.press('Escape');
  await page.waitForTimeout(250);
  assert(!await page.locator('.cinema').evaluate(el=>el.classList.contains('immersive')));
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'');
  assert(await page.locator('.expand').evaluate(el=>el===document.activeElement), 'Focus returns to entry');
  await page.locator('.expand').click();
  await page.waitForFunction(()=>!!document.fullscreenElement);
  await page.evaluate(()=>document.exitFullscreen());
  await page.waitForFunction(()=>!document.querySelector('.cinema').classList.contains('immersive'));
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'', 'External native exit restores body');
  assert(await page.locator('.expand').evaluate(el=>el===document.activeElement), 'External native exit restores focus');
  console.log('Native desktop: fullscreen, idle fade, pause/resume, drawer, selection, Escape/focus passed');

  const mobile=await browser.newPage({viewport:{width:390,height:844}, isMobile:true, hasTouch:true});
  mobile.on('pageerror', error=>errors.push(error.message));
  await mobile.addInitScript(()=> { Element.prototype.requestFullscreen=undefined; });
  await mobile.goto(base, {waitUntil:'networkidle'});
  await mobile.locator('.artwork-stage[data-ready="true"]').waitFor();
  await mobile.locator('.expand').tap();
  await mobile.locator('.cinema.immersive').waitFor();
  await mobile.waitForTimeout(200);
  assert(!await mobile.evaluate(()=>document.fullscreenElement));
  if (process.env.GALLERY_SHOT_DIR) await mobile.screenshot({path:`${process.env.GALLERY_SHOT_DIR}/cinema-fullscreen-mobile.png`});
  assert(await mobile.evaluate(()=>document.querySelector('.cinema').getBoundingClientRect().height===innerHeight), 'Fallback fills viewport');
  await mobile.waitForTimeout(3700);
  const hiddenButton = await mobile.locator('.enter').boundingBox();
  await mobile.touchscreen.tap(hiddenButton.x + hiddenButton.width / 2, hiddenButton.y + hiddenButton.height / 2);
  assert.equal(await mobile.locator('.cinema').getAttribute('data-touring'),'true', 'Reveal tap does not pause');
  assert(!await mobile.locator('.cinema').evaluate(el=>el.classList.contains('controls-hidden')));
  await mobile.locator('.enter').tap();
  await mobile.waitForTimeout(3600);
  assert(!await mobile.locator('.cinema').evaluate(el=>el.classList.contains('controls-hidden')), 'Paused controls remain visible');
  await mobile.locator('.exit-fullscreen').tap();
  assert.equal(await mobile.evaluate(()=>document.body.style.overflow),'');
  await mobile.setViewportSize({width:844,height:390});
  await mobile.locator('.expand').tap();
  await mobile.waitForTimeout(350);
  if (process.env.GALLERY_SHOT_DIR) await mobile.screenshot({path:`${process.env.GALLERY_SHOT_DIR}/cinema-fullscreen-landscape.png`});
  assert(await mobile.locator('.journey').evaluate(el=>{const box=el.getBoundingClientRect();return box.left>=0 && box.right<=innerWidth && box.top>=0 && box.bottom<=innerHeight;}),'Landscape controls fit viewport');
  assert.equal(await mobile.locator('.collection').evaluate(el=>getComputedStyle(el).display),'none','Closed collection does not flash on fullscreen entry');
  await mobile.locator('.exit-fullscreen').tap();
  console.log('Mobile fallback: viewport, tap reveal, paused visibility, exit passed');
  assert.deepEqual(errors,[]);
} finally { await browser.close(); }
